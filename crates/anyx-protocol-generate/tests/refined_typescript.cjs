const assert = require('node:assert/strict');
const m = require(process.argv[2]);
(async () => {
  assert.equal(m.Revision(1n), 1n);
  for (const n of [10n, 29n]) assert.equal(m.Limit(n), n);
  assert.throws(() => m.Revision(0n), /Revision.*0.*1 <= _.*at least 1/);
  assert.throws(() => m.Limit(30n), /less than 30/);
  assert.throws(() => m.Revision(1), /integer/);
  assert.equal(m.Probability(0.5), 0.5);
  assert.throws(() => m.Probability(1.1), /at most 1/);
  assert.throws(() => m.Probability(NaN));
  assert.equal(m.ScorePath('a.poentaro'), 'a.poentaro');
  assert.throws(() => m.ScorePath('bad.txt'), /ends with/);
  assert.equal(m.ShortText('😀'), '😀');
  assert.equal(m.ShortText('中文語'), '中文語');
  assert.throws(() => m.ShortText(''), /length at least 1/);
  assert.throws(() => m.ShortText('abcd'), /length at most 3/);
  assert.equal(m.Large(9007199254740993n), 9007199254740993n);
  assert.throws(() => m.Large(9007199254740992n));
  assert.equal(m.Linear(29n), 29n);
  assert.throws(() => m.Linear(30n));
  assert.throws(() => m.Linear(0n));
  assert.equal(m.ContainsZero("\0" + "1"), "\0" + "1");
  assert.throws(() => m.ContainsZero("01"));
  assert.equal(m.Wide(1n), 1n);
  assert.throws(() => m.Wide(3n));
  assert.equal(m.OutsideRange(0n), 0n);
  assert.equal(m.OutsideRange(4n), 4n);
  assert.throws(() => m.OutsideRange(2n));
  assert.deepEqual(m.TrueOnly({ kind: 'true' }), { kind: 'true' });
  assert.throws(() => m.TrueOnly({ kind: 'false' }));
  assert.deepEqual(m.Names(['a']), ['a']);
  assert.throws(() => m.Names([]));
  const requests = [];
  let response = 'RETURNS 10';
  const client = new m.Client(async request => { requests.push(request); return response; });
  assert.equal((await client.limit(10n)).value, 10n);
  const sent = requests.length;
  await assert.rejects(client.limit(30n), /less than 30/);
  assert.equal(requests.length, sent);
  response = 'RETURNS 30';
  await assert.rejects(client.limit(10n), /less than 30/);
  response = 'RETURNS 0';
  await assert.rejects(client.writeAt(m.ScorePath('a.poentaro'), m.Revision(1n)), /Revision.*at least 1/);
  response = 'RETURNS { value 10 }';
  assert.equal((await client.boxed({value:10n})).value.value, 10n);
  await assert.rejects(client.boxed({value:30n}), /less than 30/);
  response = 'RETURNS { path "a.poentaro", revision 1 }';
  const summary = await client.summary({path:m.ScorePath('a.poentaro'),revision:m.Revision(1n)});
  assert.equal(summary.value.limit, 10n);
  await assert.rejects(client.summary({path:'bad.txt',revision:1n}), /ends with/);
  process.stdout.write(JSON.stringify(requests));
})().catch(e => { console.error(e); process.exitCode = 1; });
