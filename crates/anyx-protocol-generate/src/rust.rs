//! The Rust module of a schema: its types, a `Server` trait with `handle`,
//! and a `Client`, all in one flat module.

use std::fmt::Write;

use anyx_protocol::schema::{Field, Method, Parameter, Schema, Shape, Shaped, Type, TypeKind};

use crate::names::{doc_comment, pascal_case, raw_string, snake_case};
use crate::{Error, error_enum_name, method_words, rust_type_taken, type_parameter_name};

const IMPORTS: &str = "use anyx_protocol::client::{CallError, Transport};\nuse anyx_protocol::{FieldsBuilder, FieldsReader, FromValue, IntoValue, Value};\n\n";

pub fn rust(schema: &Schema) -> Result<String, Error> {
    crate::check_names(schema)?;
    let mut out = String::new();
    writeln!(
        out,
        "// Generated by anyx-protocol-generate from the `{}` schema. To change it, change the schema and generate it again.\n",
        schema.name
    )
    .unwrap();
    out.push_str(
        "#![allow(clippy::all, dead_code, unused_imports, unused_mut, unused_variables)]\n\n",
    );
    out.push_str(IMPORTS);
    writeln!(
        out,
        "/// The schema as written, with explicit imports.\npub const SCHEMA_FILES: &[anyx_protocol::SchemaFile<'static>] = &[\n{}];\n",
        schema_files(schema)
    )
    .unwrap();
    out.push_str(
        "/// The schema, read once.\npub fn schema() -> &'static anyx_protocol::Schema {\n    static SCHEMA_READ: ::std::sync::LazyLock<anyx_protocol::Schema> =\n        ::std::sync::LazyLock::new(|| anyx_protocol::Schema::load(SCHEMA_FILES[0].path, |path| SCHEMA_FILES.iter().find(|file| file.path == path).map(|file| file.source.to_string()).ok_or_else(|| format!(\"missing embedded file: {path}\"))).expect(\"the generator checked the schema\"));\n    &SCHEMA_READ\n}\n\n",
    );
    body(&mut out, schema);
    Ok(out)
}

/// The entries of `SCHEMA_FILES`.
pub fn schema_files(schema: &Schema) -> String {
    schema
        .files
        .iter()
        .map(|file| {
            format!(
                "    anyx_protocol::SchemaFile {{ path: {:?}, source: {} }},\n",
                file.path,
                raw_string(&file.source)
            )
        })
        .collect()
}

/// Every declaration in the generated module.
fn body(out: &mut String, schema: &Schema) {
    for definition in schema.types.iter() {
        let name = pascal_case(&definition.name);
        let doc = doc_comment(&definition.doc, "///");
        let generics = Generics::new(schema, &definition.parameters);
        match &definition.kind {
            TypeKind::Record(fields) => record(out, schema, &doc, &name, &generics, fields),
            TypeKind::Choice(variants) => choice(out, schema, &doc, &name, &generics, variants),
            TypeKind::Distinct(underlying) => newtype(out, schema, &doc, &name, underlying),
        }
    }
    let methods: Vec<_> = schema.methods.iter().enumerate().collect();
    for (_, method) in &methods {
        if !method.errors.is_empty() {
            let errors: Vec<Shaped> = schema.errors_of(method).into_iter().cloned().collect();
            let doc = format!("/// The errors of `{}`.\n", schema.call_name(method));
            let generics = Generics::new(schema, &[]);
            choice(
                out,
                schema,
                &doc,
                &error_enum_name(schema, method),
                &generics,
                &errors,
            );
        }
    }
    root_server(out, schema);
    handle(out, schema);
    client(out, schema);
    effects(out, schema, &methods);
}

/// `r#type` as written in the generated module.
pub fn rust_type(schema: &Schema, r#type: &Type) -> String {
    match r#type {
        Type::Text => "String".to_string(),
        Type::Bytes => "Vec<u8>".to_string(),
        Type::Integer => "i64".to_string(),
        Type::Float => "f64".to_string(),
        Type::Boolean => "bool".to_string(),
        Type::Instant => "::std::time::SystemTime".to_string(),
        Type::Duration => "::std::time::Duration".to_string(),
        Type::Refined(base, _) => rust_type(schema, base),
        Type::List(item) => format!("Vec<{}>", rust_type(schema, item)),
        Type::Map(value) => format!(
            "::std::collections::BTreeMap<String, {}>",
            rust_type(schema, value)
        ),
        Type::Named(index) => {
            let definition = &schema.types[*index];
            pascal_case(&definition.name)
        }
        Type::Generic(index, arguments) => {
            let definition = &schema.types[*index];
            let arguments: Vec<String> = arguments
                .iter()
                .map(|argument| rust_type(schema, argument))
                .collect();
            format!(
                "{}<{}>",
                pascal_case(&definition.name),
                arguments.join(", ")
            )
        }
        Type::Parameter(name) => type_parameter_name(name, |taken| rust_type_taken(schema, taken)),
    }
}

/// The type parameters of a generic record or choice, which its
/// conversions need to convert too: `<Item>`, and
/// `impl<Item: IntoValue> IntoValue for PageOf<Item>`.
struct Generics {
    names: Vec<String>,
}

impl Generics {
    fn new(schema: &Schema, parameters: &[String]) -> Self {
        Generics {
            names: parameters
                .iter()
                .map(|parameter| rust_type(schema, &Type::Parameter(parameter.clone())))
                .collect(),
        }
    }

    /// `name` with its parameters: `PageOf<Item>`.
    fn of(&self, name: &str) -> String {
        match self.names.is_empty() {
            true => name.to_string(),
            false => format!("{name}<{}>", self.names.join(", ")),
        }
    }

    /// `impl` with each parameter bound by `bound`: `impl<Item: IntoValue>`.
    fn implementation(&self, bound: &str) -> String {
        match self.names.is_empty() {
            true => "impl".to_string(),
            false => format!(
                "impl<{}>",
                self.names
                    .iter()
                    .map(|name| format!("{name}: {bound}"))
                    .collect::<Vec<_>>()
                    .join(", ")
            ),
        }
    }
}

/// Whether a field may be missing from a record: `OPTIONAL` without a
/// `DEFAULT`, which the codec fills in.
pub fn may_be_missing(field: &Field) -> bool {
    field.optional && field.default.is_none()
}

fn field_type(schema: &Schema, field: &Field) -> String {
    match may_be_missing(field) {
        true => format!("Option<{}>", rust_type(schema, &field.r#type)),
        false => rust_type(schema, &field.r#type),
    }
}

fn record(
    out: &mut String,
    schema: &Schema,
    doc: &str,
    name: &str,
    generics: &Generics,
    fields: &[Field],
) {
    let declared: String = fields
        .iter()
        .map(|field| {
            format!(
                "{}    pub {}: {},\n",
                doc_comment(&field.doc, "    ///"),
                snake_case(&field.name),
                field_type(schema, field)
            )
        })
        .collect();
    let built: String = fields
        .iter()
        .map(|field| {
            let method = if may_be_missing(field) {
                "optional"
            } else {
                "field"
            };
            format!(
                ".{method}({:?}, self.{})",
                field.name,
                snake_case(&field.name)
            )
        })
        .collect();
    let read: String = fields
        .iter()
        .map(|field| {
            let method = if may_be_missing(field) {
                "optional"
            } else {
                "field"
            };
            format!(
                "{}: fields.{method}({:?})?, ",
                snake_case(&field.name),
                field.name
            )
        })
        .collect();
    let into = generics.implementation("IntoValue");
    let from = generics.implementation("FromValue");
    let name = generics.of(name);
    write!(
        out,
        "{doc}#[derive(Clone, Debug, PartialEq)]\npub struct {name} {{\n{declared}}}\n\n\
         {into} IntoValue for {name} {{\n    fn into_value(self) -> Value {{\n        Value::Record(FieldsBuilder::new(){built}.build())\n    }}\n}}\n\n\
         {from} FromValue for {name} {{\n    fn from_value(value: Value) -> Option<Self> {{\n        let Value::Record(fields) = value else {{ return None }};\n        let mut fields = FieldsReader::new(fields);\n        Some(Self {{ {read} }})\n    }}\n}}\n\n"
    )
    .unwrap();
}

/// A named type: a struct around the type underneath, which converts to and
/// from it, and is written on the wire exactly like it.
fn newtype(out: &mut String, schema: &Schema, doc: &str, name: &str, underlying: &Type) {
    if anyx_protocol::refinement::has_refinements(schema, underlying) {
        let index = schema
            .types
            .iter()
            .position(|definition| pascal_case(&definition.name) == name)
            .unwrap();
        let inner = rust_type(schema, underlying);
        write!(out, "{doc}#[derive(Clone, Debug, PartialEq)]\npub struct {name}({inner});\n\n\
            impl {name} {{\n    pub fn new(value: {inner}) -> Result<Self, String> {{\n        let wire = value.clone().into_value();\n        anyx_protocol::refinement::validate(schema(), &anyx_protocol::schema::Type::Named({index}), &wire)?;\n        Ok(Self(value))\n    }}\n    pub fn get(&self) -> &{inner} {{ &self.0 }}\n    pub fn into_inner(self) -> {inner} {{ self.0 }}\n}}\n\n\
            impl TryFrom<{inner}> for {name} {{\n    type Error = String;\n    fn try_from(value: {inner}) -> Result<Self, Self::Error> {{ Self::new(value) }}\n}}\n\n\
            impl From<{name}> for {inner} {{\n    fn from(value: {name}) -> Self {{ value.0 }}\n}}\n\n\
            impl IntoValue for {name} {{\n    fn into_value(self) -> Value {{ self.0.into_value() }}\n}}\n\n\
            impl FromValue for {name} {{\n    fn from_value(value: Value) -> Option<Self> {{\n        anyx_protocol::refinement::validate(schema(), &anyx_protocol::schema::Type::Named({index}), &value).ok()?;\n        FromValue::from_value(value).map(Self)\n    }}\n}}\n\n").unwrap();
        return;
    }
    let underlying = rust_type(schema, underlying);
    write!(
        out,
        "{doc}#[derive(Clone, Debug, PartialEq)]\npub struct {name}(pub {underlying});\n\n\
         impl From<{underlying}> for {name} {{\n    fn from(value: {underlying}) -> Self {{\n        Self(value)\n    }}\n}}\n\n\
         impl From<{name}> for {underlying} {{\n    fn from(value: {name}) -> Self {{\n        value.0\n    }}\n}}\n\n\
         impl IntoValue for {name} {{\n    fn into_value(self) -> Value {{\n        self.0.into_value()\n    }}\n}}\n\n\
         impl FromValue for {name} {{\n    fn from_value(value: Value) -> Option<Self> {{\n        FromValue::from_value(value).map(Self)\n    }}\n}}\n\n"
    )
    .unwrap();
}

/// A choice, or a method's errors: an enum with a variant per shape.
fn choice(
    out: &mut String,
    schema: &Schema,
    doc: &str,
    name: &str,
    generics: &Generics,
    variants: &[Shaped],
) {
    let declared: String = variants
        .iter()
        .map(|variant| {
            let doc = doc_comment(&variant.doc, "    ///");
            let variant_name = pascal_case(&variant.shape.text);
            match variant.shape.parameters.is_empty() {
                true => format!("{doc}    {variant_name},\n"),
                false => format!(
                    "{doc}    {variant_name} {{ {} }},\n",
                    variant
                        .shape
                        .parameters
                        .iter()
                        .map(|parameter| format!(
                            "{}: {}",
                            snake_case(&parameter.name),
                            rust_type(schema, &parameter.r#type)
                        ))
                        .collect::<Vec<_>>()
                        .join(", ")
                ),
            }
        })
        .collect();
    let into: String = variants
        .iter()
        .map(|variant| {
            let shape = &variant.shape;
            format!(
                "            {name}::{}{} => Value::Variant {{ shape: {:?}.to_string(), arguments: vec![{}] }},\n",
                pascal_case(&shape.text),
                bindings(shape),
                shape.text,
                shape
                    .parameters
                    .iter()
                    .map(|parameter| format!("{}.into_value()", snake_case(&parameter.name)))
                    .collect::<Vec<_>>()
                    .join(", ")
            )
        })
        .collect();
    let from: String = variants
        .iter()
        .map(|variant| {
            let shape = &variant.shape;
            let fields = match shape.parameters.is_empty() {
                true => String::new(),
                false => format!(
                    " {{ {} }}",
                    shape
                        .parameters
                        .iter()
                        .map(|parameter| format!(
                            "{}: FromValue::from_value(arguments.next()?)?",
                            snake_case(&parameter.name)
                        ))
                        .collect::<Vec<_>>()
                        .join(", ")
                ),
            };
            format!(
                "            {:?} => {name}::{}{fields},\n",
                shape.text,
                pascal_case(&shape.text)
            )
        })
        .collect();
    let declared_name = generics.of(name);
    let into_implementation = generics.implementation("IntoValue");
    let from_implementation = generics.implementation("FromValue");
    write!(
        out,
        "{doc}#[derive(Clone, Debug, PartialEq)]\npub enum {declared_name} {{\n{declared}}}\n\n\
         {into_implementation} IntoValue for {declared_name} {{\n    fn into_value(self) -> Value {{\n        match self {{\n{into}        }}\n    }}\n}}\n\n\
         {from_implementation} FromValue for {declared_name} {{\n    fn from_value(value: Value) -> Option<Self> {{\n        let Value::Variant {{ shape, arguments }} = value else {{ return None }};\n        let mut arguments = arguments.into_iter();\n        Some(match shape.as_str() {{\n{from}            _ => return None,\n        }})\n    }}\n}}\n\n"
    )
    .unwrap();
}

/// ` { a, b }` to bind a variant's parameters, or nothing.
fn bindings(shape: &Shape) -> String {
    match shape.parameters.is_empty() {
        true => String::new(),
        false => format!(
            " {{ {} }}",
            shape
                .parameters
                .iter()
                .map(|parameter| snake_case(&parameter.name))
                .collect::<Vec<_>>()
                .join(", ")
        ),
    }
}

fn parameters(schema: &Schema, parameters: &[Parameter]) -> String {
    parameters
        .iter()
        .map(|parameter| {
            format!(
                ", {}: {}",
                snake_case(&parameter.name),
                rust_type(schema, &parameter.r#type)
            )
        })
        .collect()
}

/// The Rust type of what `method` returns: `()` for `RETURNS NOTHING`.
fn returned_value(schema: &Schema, method: &Method) -> String {
    method.returns.as_ref().map_or_else(
        || "()".to_string(),
        |returns| rust_type(schema, &returns.r#type),
    )
}

fn returned(schema: &Schema, method: &Method) -> String {
    let value = returned_value(schema, method);
    match method.errors.is_empty() {
        true => value,
        false => format!("Result<{value}, {}>", error_enum_name(schema, method)),
    }
}

fn method_doc(schema: &Schema, method: &Method) -> String {
    let mut doc = doc_comment(&method.doc, "    ///");
    if !doc.is_empty() {
        doc.push_str("    ///\n");
    }
    match &method.returns {
        Some(returns) => writeln!(
            doc,
            "    /// `{}`, returning `{}`.",
            schema.call_name(method),
            returns.name
        ),
        None => writeln!(
            doc,
            "    /// `{}`, returning nothing.",
            schema.call_name(method)
        ),
    }
    .unwrap();
    doc.push_str("    ///\n");
    doc.push_str(&doc_comment(&Some(crate::effects_doc(method)), "    ///"));
    if let Some(examples) = crate::examples_doc(method) {
        doc.push_str("    ///\n");
        doc.push_str(&doc_comment(&Some(examples), "    ///"));
    }
    doc
}

/// The protocol methods in the server trait.
fn trait_methods(schema: &Schema) -> String {
    let methods: String = schema
        .methods
        .iter()
        .map(|method| {
            format!(
                "{}    async fn {}(&self{}) -> Result<{}, Self::Error>;\n\n",
                method_doc(schema, method),
                snake_case(&method_words(schema, method)),
                parameters(schema, &method.shape.parameters),
                returned(schema, method)
            )
        })
        .collect();
    methods.trim_end_matches('\n').to_string() + "\n"
}

fn root_server(out: &mut String, schema: &Schema) {
    write!(
        out,
        "/// The protocol methods, for a server to implement. An `Err` is the server's own failure: the\n/// caller gets `INTERNAL ERROR`, and the calls after it don't run.\n#[allow(async_fn_in_trait)]\npub trait Server {{\n    type Error;\n\n{}}}\n\n",
        trait_methods(schema)
    )
    .unwrap();
}

fn handle(out: &mut String, schema: &Schema) {
    let arms: String = schema
        .methods
        .iter()
        .enumerate()
        .map(|(index, method)| {
            let arguments: String = method
                .shape
                .parameters
                .iter()
                .map(|_| ", anyx_protocol::server::argument(&mut arguments)")
                .collect();
            let wrap = if method.errors.is_empty() {
                "value"
            } else {
                "result"
            };
            format!(
                "            {index} => anyx_protocol::server::{wrap}(<S as Server>::{}(implementation{arguments}).await),\n",
                snake_case(&method_words(schema, method))
            )
        })
        .collect();
    write!(
        out,
        "/// Runs `request` against `implementation` and writes the response. Every\n/// call runs, in order, until one fails with an internal error, which\n/// `on_internal_error` hears; the calls after it don't run.\n\
         pub async fn handle<S: Server>(implementation: &S, request: &str, mut on_internal_error: impl FnMut(<S as Server>::Error)) -> String {{\n\
         \x20   let schema = schema();\n\
         \x20   let calls = match anyx_protocol::server::read_request(schema, request) {{\n        Ok(calls) => calls,\n        Err(response) => return response,\n    }};\n\
         \x20   let mut outcomes = Vec::new();\n\
         \x20   let mut stopped = false;\n\
         \x20   for call in &calls {{\n\
         \x20       if stopped {{\n            outcomes.push(anyx_protocol::Outcome::NotRun);\n            continue;\n        }}\n\
         \x20       let mut arguments = call.arguments.clone().into_iter();\n\
         \x20       let outcome = match call.method {{\n{arms}            {introspection} => Ok::<_, <S as Server>::Error>(anyx_protocol::server::introspect(schema)),\n            _ => unreachable!(\"the codec read a method of the schema\"),\n        }};\n\
         \x20       let outcome = outcome.unwrap_or_else(|error| {{\n            on_internal_error(error);\n            stopped = true;\n            anyx_protocol::Outcome::InternalError\n        }});\n\
         \x20       if anyx_protocol::server::validate_outcome(schema, call, &outcome).is_err() {{\n            stopped = true;\n            outcomes.push(anyx_protocol::Outcome::InternalError);\n        }} else {{\n            outcomes.push(outcome);\n        }}\n    }}\n\
         \x20   anyx_protocol::server::respond(schema, &calls, outcomes)\n}}\n\n",
        introspection = schema.introspection(),
    )
    .unwrap();
}

/// A constant of each method's markers, `READ_EFFECTS` for `read _`, for a
/// tool to decide whether to retry a call or ask before sending it.
fn effects(out: &mut String, schema: &Schema, methods: &[(usize, &Method)]) {
    for (_, method) in methods {
        let undone_by = match &method.undone_by {
            Some(undo) => format!("Some({:?})", undo.text),
            None => "None".to_string(),
        };
        write!(
            out,
            "/// What a call of `{}` may do. {}\npub const {}_EFFECTS: anyx_protocol::client::Effects = anyx_protocol::client::Effects {{\n    read_only: {},\n    idempotent: {},\n    undone_by: {undone_by},\n}};\n\n",
            schema.call_name(method),
            crate::effects_doc(method),
            snake_case(&method_words(schema, method)).to_uppercase(),
            method.effect.read_only(),
            method.effect.idempotent(),
        )
        .unwrap();
    }
}

/// The client owns its transport.
fn client(out: &mut String, schema: &Schema) {
    let methods: String = schema.methods.iter().enumerate()
        .map(|(index, method)| {
            let errors = match method.errors.is_empty() {
                true => "::std::convert::Infallible".to_string(),
                false => error_enum_name(schema, method),
            };
            let arguments = method
                .shape
                .parameters
                .iter()
                .map(|parameter| format!("{}.into_value()", snake_case(&parameter.name)))
                .collect::<Vec<_>>()
                .join(", ");
            format!(
                "{}    pub async fn {}(&self{}) -> Result<{}, CallError<{errors}, T::Error>> {{\n        anyx_protocol::client::call(&self.transport, schema(), {index}, vec![{arguments}]).await\n    }}\n\n",
                method_doc(schema, method),
                snake_case(&method_words(schema, method)),
                parameters(schema, &method.shape.parameters),
                returned_value(schema, method),
            )
        })
        .collect();
    let introspection = format!(
        "    /// `SCHEMA`, returning the guide to the schema.\n    pub async fn schema(&self) -> Result<String, CallError<::std::convert::Infallible, T::Error>> {{\n        anyx_protocol::client::call(&self.transport, schema(), {}, vec![]).await\n    }}\n\n",
        schema.introspection()
    );
    let members = (methods + &introspection)
        .trim_end_matches('\n')
        .to_string()
        + "\n";
    write!(
            out,
            "/// Calls the methods of the schema through a [`Transport`], one call per\n/// request.\npub struct Client<T> {{\n    pub transport: T,\n}}\n\n\
             impl<T: Transport> Client<T> {{\n    pub fn new(transport: T) -> Self {{\n        Self {{ transport }}\n    }}\n\n{members}}}\n\n"
        )
    .unwrap();
}
