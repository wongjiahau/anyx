//! The Rust module of a schema: its types, a `Server` trait with `handle`,
//! and a `Client`, all in one flat module.

use std::fmt::Write;

use anyx_protocol::schema::{
    Field, Method, Parameter, Schema, Shape, ShapePart, Shaped, Type, TypeKind, slot_types,
};

use crate::names::{doc_comment, pascal_case, raw_string, snake_case};
use crate::{Error, error_enum_name, method_words, rust_type_taken, type_parameter_name};

const IMPORTS: &str = "use anyx_protocol::client::{CallError, Transport};\nuse anyx_protocol::{FieldsBuilder, FieldsReader, FromValue, IntoValue, Value};\n\n";

pub fn rust(schema: &Schema) -> Result<String, Error> {
    crate::check_names(schema)?;
    let variants = crate::rust_variants(schema).map_err(|r#type| {
        let name = schema.type_name(r#type);
        let message = match r#type {
            Type::Variant(_) => format!(
                "found the standalone variant `{name}` with slots; give it a name with a `TYPE ALIAS` of a one-member union `[| … |]` to generate Rust"
            ),
            _ => format!(
                "found the union `{name}`; expected only nullable unions, `T?`, in generated Rust, which writes them as `Option<T>`; other unions wait for named types"
            ),
        };
        Error { message }
    })?;
    let mut out = String::new();
    writeln!(
        out,
        "// Generated by anyx-protocol-generate from the `{}` schema. To change it, change the schema and generate it again.\n",
        schema.name
    )
    .unwrap();
    out.push_str(
        "#![allow(clippy::all, dead_code, unused_imports, unused_mut, unused_variables)]\n\n",
    );
    out.push_str(IMPORTS);
    writeln!(
        out,
        "/// The schema as written, with explicit imports.\npub const SCHEMA_FILES: &[anyx_protocol::SchemaFile<'static>] = &[\n{}];\n",
        schema_files(schema)
    )
    .unwrap();
    out.push_str(
        "/// The schema, read once.\npub fn schema() -> &'static anyx_protocol::Schema {\n    static SCHEMA_READ: ::std::sync::LazyLock<anyx_protocol::Schema> =\n        ::std::sync::LazyLock::new(|| anyx_protocol::Schema::load(SCHEMA_FILES[0].path, |path| SCHEMA_FILES.iter().find(|file| file.path == path).map(|file| file.source.to_string()).ok_or_else(|| format!(\"missing embedded file: {path}\"))).expect(\"the generator checked the schema\"));\n    &SCHEMA_READ\n}\n\n",
    );
    if !variants.is_empty() {
        out.push_str("#[allow(non_camel_case_types)]\npub mod variants {\n");
        for shape in variants {
            let name = variant_type_name(shape);
            writeln!(out, r#"
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct {name};
impl ::anyx_protocol::IntoValue for {name} {{
    fn into_value(self) -> ::anyx_protocol::Value {{
        ::anyx_protocol::Value::Variant {{ shape: {wire:?}.to_string(), arguments: ::std::vec::Vec::new() }}
    }}
}}
impl ::anyx_protocol::FromValue for {name} {{
    fn from_value(value: ::anyx_protocol::Value) -> ::std::option::Option<Self> {{
        match value {{
            ::anyx_protocol::Value::Variant {{ shape, arguments }} if shape == {wire:?} && arguments.is_empty() => ::std::option::Option::Some(Self),
            _ => ::std::option::Option::None,
        }}
    }}
}}"#, wire = shape.text).unwrap();
        }
        out.push_str("}\n\n");
    }
    body(&mut out, schema);
    Ok(out)
}

/// The entries of `SCHEMA_FILES`.
pub fn schema_files(schema: &Schema) -> String {
    schema
        .files
        .iter()
        .map(|file| {
            format!(
                "    anyx_protocol::SchemaFile {{ path: {:?}, source: {} }},\n",
                file.path,
                raw_string(&file.source)
            )
        })
        .collect()
}

/// Every declaration in the generated module.
fn body(out: &mut String, schema: &Schema) {
    for (index, definition) in schema.types.iter().enumerate() {
        let name = pascal_case(&definition.name);
        let doc = doc_comment(&definition.doc, "///");
        let generics = Generics::new(schema, &definition.parameters);
        match &definition.kind {
            TypeKind::Record(fields) => record(out, schema, &doc, &name, &generics, fields),
            TypeKind::Variants(variants) => choice(out, schema, &doc, &name, &generics, variants),
            TypeKind::Distinct {
                constructor,
                underlying,
            } => newtype(out, schema, &doc, &name, index, constructor, underlying),
        }
    }
    let methods: Vec<_> = schema.methods.iter().enumerate().collect();
    for (_, method) in &methods {
        if !method.errors.is_empty() {
            let errors: Vec<Shaped> = schema.errors_of(method).into_iter().cloned().collect();
            let doc = format!("/// The errors of `{}`.\n", schema.call_name(method));
            let generics = Generics::new(schema, &[]);
            let name = error_enum_name(schema, method);
            choice(out, schema, &doc, &name, &generics, &errors);
            for group in &method.error_groups {
                error_group_conversion(out, schema, &name, group);
            }
        }
    }
    root_server(out, schema);
    handle(out, schema);
    client(out, schema);
    effects(out, schema, &methods);
}

/// Preserve word boundaries so distinct shapes have distinct Rust names.
fn variant_type_name(shape: &Shape) -> String {
    let name = shape
        .text
        .split(' ')
        .map(pascal_case)
        .collect::<Vec<_>>()
        .join("_");
    if name == "Self" {
        "Self_".to_string()
    } else {
        name
    }
}

/// `r#type` as written in the generated module.
pub fn rust_type(schema: &Schema, r#type: &Type) -> String {
    match r#type {
        Type::Text => "String".to_string(),
        Type::Bytes => "Vec<u8>".to_string(),
        Type::Integer => "i64".to_string(),
        Type::Float => "f64".to_string(),
        Type::Instant => "::std::time::SystemTime".to_string(),
        Type::Duration => "::std::time::Duration".to_string(),
        Type::Refined(base, _) => rust_type(schema, base),
        Type::List(item) => format!("Vec<{}>", rust_type(schema, item)),
        Type::Map(value) => format!(
            "::std::collections::BTreeMap<String, {}>",
            rust_type(schema, value)
        ),
        Type::Named(index) => {
            let definition = &schema.types[*index];
            pascal_case(&definition.name)
        }
        Type::Generic(index, arguments) => {
            let definition = &schema.types[*index];
            let arguments: Vec<String> = arguments
                .iter()
                .map(|argument| rust_type(schema, argument))
                .collect();
            format!(
                "{}<{}>",
                pascal_case(&definition.name),
                arguments.join(", ")
            )
        }
        Type::Parameter(name) => type_parameter_name(name, |taken| rust_type_taken(schema, taken)),
        Type::Variant(shape) => format!("variants::{}", variant_type_name(shape)),
        Type::Union(_) => match schema.nullable_item(r#type) {
            Some(item) => format!("Option<{}>", rust_type(schema, item)),
            // `rust` reports any other union before it writes a type.
            None => "()".to_string(),
        },
        Type::Tuple(slots, _) => format!(
            "({})",
            slots
                .iter()
                .map(|slot| rust_type(schema, slot))
                .collect::<Vec<_>>()
                .join(", ")
        ),
    }
}

/// The type parameters of a generic record or union of variants, which its
/// conversions need to convert too: `<Item>`, and
/// `impl<Item: IntoValue> IntoValue for PageOf<Item>`.
struct Generics {
    names: Vec<String>,
}

impl Generics {
    fn new(schema: &Schema, parameters: &[String]) -> Self {
        Generics {
            names: parameters
                .iter()
                .map(|parameter| rust_type(schema, &Type::Parameter(parameter.clone())))
                .collect(),
        }
    }

    /// `name` with its parameters: `PageOf<Item>`.
    fn of(&self, name: &str) -> String {
        match self.names.is_empty() {
            true => name.to_string(),
            false => format!("{name}<{}>", self.names.join(", ")),
        }
    }

    /// `impl` with each parameter bound by `bound`: `impl<Item: IntoValue>`.
    fn implementation(&self, bound: &str) -> String {
        match self.names.is_empty() {
            true => "impl".to_string(),
            false => format!(
                "impl<{}>",
                self.names
                    .iter()
                    .map(|name| format!("{name}: {bound}"))
                    .collect::<Vec<_>>()
                    .join(", ")
            ),
        }
    }
}

fn slot_ident(name: &str) -> String {
    match name {
        "self" | "super" | "crate" => format!("{name}_"),
        _ => snake_case(name),
    }
}

pub(crate) fn field_slots_name(record: &str, field: &Field) -> String {
    format!("{record}{}Slots", pascal_case(&field.name))
}

fn field_slots(
    out: &mut String,
    schema: &Schema,
    name: &str,
    types: &[Type],
    names: &[String],
    generics: &Generics,
) -> String {
    let declared: String = names
        .iter()
        .zip(types)
        .map(|(slot, ty)| format!("    pub {}: {},\n", slot_ident(slot), rust_type(schema, ty)))
        .collect();
    let built = names
        .iter()
        .map(|slot| format!("self.{}.into_value()", slot_ident(slot)))
        .collect::<Vec<_>>()
        .join(", ");
    let read: String = names
        .iter()
        .map(|slot| {
            format!(
                "{}: FromValue::from_value(slots.next()?)?, ",
                slot_ident(slot)
            )
        })
        .collect();
    let into = generics.implementation("IntoValue");
    let from = generics.implementation("FromValue");
    let name = generics.of(name);
    writeln!(out, "#[derive(Clone, Debug, PartialEq)]\npub struct {name} {{\n{declared}}}\n\n\
        {into} IntoValue for {name} {{\n    fn into_value(self) -> Value {{\n        Value::Tuple(vec![{built}])\n    }}\n}}\n\n\
        {from} FromValue for {name} {{\n    fn from_value(value: Value) -> Option<Self> {{\n        let Value::Tuple(slots) = value else {{ return None }};\n        if slots.len() != {} {{ return None }}\n        let mut slots = slots.into_iter();\n        Some(Self {{ {read} }})\n    }}\n}}\n", names.len()).unwrap();
    name
}

fn record(
    out: &mut String,
    schema: &Schema,
    doc: &str,
    name: &str,
    generics: &Generics,
    fields: &[Field],
) {
    let declared: String = fields
        .iter()
        .map(|field| {
            let ty = match &field.r#type {
                Type::Tuple(types, names) => {
                    let parameters = field
                        .r#type
                        .parameters()
                        .into_iter()
                        .map(str::to_owned)
                        .collect::<Vec<_>>();
                    let generics = Generics::new(schema, &parameters);
                    field_slots(
                        out,
                        schema,
                        &field_slots_name(name, field),
                        types,
                        names,
                        &generics,
                    )
                }
                ty => rust_type(schema, ty),
            };
            format!(
                "{}    pub {}: {},\n",
                doc_comment(&field.doc, "    ///"),
                slot_ident(&field.name),
                ty
            )
        })
        .collect();
    let built: String = fields
        .iter()
        .map(|field| format!(".field({:?}, self.{})", field.name, slot_ident(&field.name)))
        .collect();
    let read: String = fields
        .iter()
        .map(|field| {
            format!(
                "{}: fields.field({:?})?, ",
                slot_ident(&field.name),
                field.name
            )
        })
        .collect();
    let into = generics.implementation("IntoValue");
    let from = generics.implementation("FromValue");
    let name = generics.of(name);
    write!(
        out,
        "{doc}#[derive(Clone, Debug, PartialEq)]\npub struct {name} {{\n{declared}}}\n\n\
         {into} IntoValue for {name} {{\n    fn into_value(self) -> Value {{\n        Value::Record(FieldsBuilder::new(){built}.build())\n    }}\n}}\n\n\
         {from} FromValue for {name} {{\n    fn from_value(value: Value) -> Option<Self> {{\n        let Value::Record(fields) = value else {{ return None }};\n        let mut fields = FieldsReader::new(fields);\n        Some(Self {{ {read} }})\n    }}\n}}\n\n"
    )
    .unwrap();
}

/// A named type: a tuple struct with a field for each slot, written as a
/// value of its constructor's shape, `File Id "a"`. With one slot it
/// converts to and from what that slot holds. A refined slot keeps its
/// fields private, so a value is only made through `new`, which checks it.
fn newtype(
    out: &mut String,
    schema: &Schema,
    doc: &str,
    name: &str,
    index: usize,
    constructor: &[ShapePart],
    underlying: &Type,
) {
    let generics = Generics::new(schema, &schema.types[index].parameters);
    let applied = generics.of(name);
    let generic_impl = generics.of("impl");
    let into_impl = generics.implementation("IntoValue");
    let from_impl = generics.implementation("FromValue");
    let marker = if generics.names.is_empty() {
        String::new()
    } else {
        let names = generics.names.join(", ");
        format!("::std::marker::PhantomData<fn({names}) -> ({names},)>")
    };
    let marker_value = "::std::marker::PhantomData";
    let slots: Vec<String> = slot_types(constructor, underlying)
        .into_iter()
        .map(|slot| rust_type(schema, slot))
        .collect();
    let shape = ShapePart::text(constructor);
    let refined = anyx_protocol::refinement::has_refinements(schema, underlying);
    let visibility = if refined { "" } else { "pub " };
    let bound: Vec<String> = (0..slots.len())
        .map(|index| format!("slot_{index}"))
        .collect();
    let (declared, pattern, construct) = match slots.as_slice() {
        [] if marker.is_empty() => (
            format!("pub struct {name};"),
            name.to_string(),
            name.to_string(),
        ),
        [] => (
            format!("pub struct {applied}({marker});"),
            format!("{name}(_)"),
            format!("{name}({marker_value})"),
        ),
        [slot] if marker.is_empty() => (
            format!("pub struct {applied}({visibility}{slot});"),
            format!("{name}(slot_0)"),
            format!("{name}(slot_0)"),
        ),
        [slot] => (
            format!("pub struct {applied}({visibility}{slot}, {marker});"),
            format!("{name}(slot_0, _)"),
            format!("{name}(slot_0, {marker_value})"),
        ),
        _ => {
            let Type::Tuple(_, names) = underlying else {
                unreachable!()
            };
            let fields: Vec<_> = names.iter().map(|slot| slot_ident(slot)).collect();
            let declarations: String = slots
                .iter()
                .zip(&fields)
                .map(|(ty, field)| format!("    {visibility}{field}: {ty},\n"))
                .collect();
            let bindings = fields
                .iter()
                .zip(&bound)
                .map(|(field, binding)| format!("{field}: {binding}"))
                .collect::<Vec<_>>()
                .join(", ");
            let (marker_field, ignore_marker, set_marker) = if marker.is_empty() {
                (String::new(), "", "")
            } else {
                (
                    format!("    __anyx_marker: {marker},\n"),
                    ", ..",
                    ", __anyx_marker: ::std::marker::PhantomData",
                )
            };
            (
                format!("pub struct {applied} {{\n{declarations}{marker_field}}}"),
                format!("{name} {{ {bindings}{ignore_marker} }}"),
                format!("{name} {{ {bindings}{set_marker} }}"),
            )
        }
    };
    let into = bound
        .iter()
        .map(|slot| format!("{slot}.into_value()"))
        .collect::<Vec<_>>()
        .join(", ");
    let read = bound
        .iter()
        .map(|slot| format!("let {slot} = FromValue::from_value(arguments.next()?)?;"))
        .collect::<Vec<_>>()
        .join("\n                ");
    let check = match refined {
        true => format!(
            "anyx_protocol::refinement::validate(schema(), &anyx_protocol::schema::Type::Named({index}), &value).ok()?;\n        "
        ),
        false => String::new(),
    };
    write!(
        out,
        "{doc}#[derive(Clone, Debug, PartialEq)]\n{declared}\n\n\
         {into_impl} IntoValue for {applied} {{\n    fn into_value(self) -> Value {{\n        let {pattern} = self;\n        Value::Variant {{ shape: {shape:?}.to_string(), arguments: vec![{into}] }}\n    }}\n}}\n\n\
         {from_impl} FromValue for {applied} {{\n    fn from_value(value: Value) -> Option<Self> {{\n        {check}match value {{\n            Value::Variant {{ shape, arguments }} if shape == {shape:?} && arguments.len() == {count} => {{\n                let mut arguments = arguments.into_iter();\n                {read}\n                Some({construct})\n            }}\n            _ => None,\n        }}\n    }}\n}}\n\n",
        count = slots.len(),
    )
    .unwrap();
    let parameters = slots
        .iter()
        .zip(&bound)
        .map(|(slot, bound)| format!("{bound}: {slot}"))
        .collect::<Vec<_>>()
        .join(", ");
    if !marker.is_empty() {
        let signature = if refined {
            let checked_impl = generics.implementation("IntoValue + Clone");
            format!(
                "{checked_impl} {applied} {{\n    pub fn new({parameters}) -> Result<Self, String> {{\n        let value = {construct};\n        anyx_protocol::refinement::validate(schema(), &anyx_protocol::schema::Type::Named({index}), &value.clone().into_value())?;\n        Ok(value)\n    }}\n}}\n"
            )
        } else {
            format!(
                "{generic_impl} {applied} {{\n    pub fn new({parameters}) -> Self {{\n        {construct}\n    }}\n}}\n"
            )
        };
        writeln!(out, "{signature}").unwrap();
        if let [inner] = slots.as_slice() {
            write!(
                out,
                "{generic_impl} {applied} {{\n    pub fn get(&self) -> &{inner} {{\n        &self.0\n    }}\n    pub fn into_inner(self) -> {inner} {{\n        self.0\n    }}\n}}\n\n"
            )
            .unwrap();
        }
        return;
    }
    if refined {
        write!(
            out,
            "impl {name} {{\n    pub fn new({parameters}) -> Result<Self, String> {{\n        let value = {pattern};\n        anyx_protocol::refinement::validate(schema(), &anyx_protocol::schema::Type::Named({index}), &value.clone().into_value())?;\n        Ok(value)\n    }}\n}}\n\n"
        )
        .unwrap();
    }
    let [inner] = slots.as_slice() else {
        return;
    };
    match refined {
        true => write!(
            out,
            "impl {name} {{\n    pub fn get(&self) -> &{inner} {{\n        &self.0\n    }}\n    pub fn into_inner(self) -> {inner} {{\n        self.0\n    }}\n}}\n\n\
             impl TryFrom<{inner}> for {name} {{\n    type Error = String;\n    fn try_from(value: {inner}) -> Result<Self, Self::Error> {{\n        Self::new(value)\n    }}\n}}\n\n"
        ),
        false => write!(
            out,
            "impl From<{inner}> for {name} {{\n    fn from(value: {inner}) -> Self {{\n        Self(value)\n    }}\n}}\n\n"
        ),
    }
    .unwrap();
    write!(
        out,
        "impl From<{name}> for {inner} {{\n    fn from(value: {name}) -> Self {{\n        value.0\n    }}\n}}\n\n"
    )
    .unwrap();
}

/// A union of variants, or a method's errors: an enum with a variant per shape.
fn choice(
    out: &mut String,
    schema: &Schema,
    doc: &str,
    name: &str,
    generics: &Generics,
    variants: &[Shaped],
) {
    let declared: String = variants
        .iter()
        .map(|variant| {
            let doc = doc_comment(&variant.doc, "    ///");
            let variant_name = pascal_case(&variant.shape.text);
            match variant.shape.parameters.is_empty() {
                true => format!("{doc}    {variant_name},\n"),
                false => format!(
                    "{doc}    {variant_name} {{ {} }},\n",
                    variant
                        .shape
                        .parameters
                        .iter()
                        .map(|parameter| format!(
                            "{}: {}",
                            snake_case(&parameter.name),
                            rust_type(schema, &parameter.r#type)
                        ))
                        .collect::<Vec<_>>()
                        .join(", ")
                ),
            }
        })
        .collect();
    let into: String = variants
        .iter()
        .map(|variant| {
            let shape = &variant.shape;
            format!(
                "            {name}::{}{} => Value::Variant {{ shape: {:?}.to_string(), arguments: vec![{}] }},\n",
                pascal_case(&shape.text),
                bindings(shape),
                shape.text,
                shape
                    .parameters
                    .iter()
                    .map(|parameter| format!("{}.into_value()", snake_case(&parameter.name)))
                    .collect::<Vec<_>>()
                    .join(", ")
            )
        })
        .collect();
    let from: String = variants
        .iter()
        .map(|variant| {
            let shape = &variant.shape;
            let fields = match shape.parameters.is_empty() {
                true => String::new(),
                false => format!(
                    " {{ {} }}",
                    shape
                        .parameters
                        .iter()
                        .map(|parameter| format!(
                            "{}: FromValue::from_value(arguments.next()?)?",
                            snake_case(&parameter.name)
                        ))
                        .collect::<Vec<_>>()
                        .join(", ")
                ),
            };
            format!(
                "            {:?} => {name}::{}{fields},\n",
                shape.text,
                pascal_case(&shape.text)
            )
        })
        .collect();
    let declared_name = generics.of(name);
    let into_implementation = generics.implementation("IntoValue");
    let from_implementation = generics.implementation("FromValue");
    write!(
        out,
        "{doc}#[derive(Clone, Debug, PartialEq)]\npub enum {declared_name} {{\n{declared}}}\n\n\
         {into_implementation} IntoValue for {declared_name} {{\n    fn into_value(self) -> Value {{\n        match self {{\n{into}        }}\n    }}\n}}\n\n\
         {from_implementation} FromValue for {declared_name} {{\n    fn from_value(value: Value) -> Option<Self> {{\n        let Value::Variant {{ shape, arguments }} = value else {{ return None }};\n        let mut arguments = arguments.into_iter();\n        Some(match shape.as_str() {{\n{from}            _ => return None,\n        }})\n    }}\n}}\n\n"
    )
    .unwrap();
}

/// `impl From<FileErrors> for ReadError`: an alias of a union of variants
/// that a method names among its errors becomes that method's error, the
/// variant of the same shape, so that `?` carries it.
fn error_group_conversion(out: &mut String, schema: &Schema, method_error: &str, group: &Type) {
    let Some((definition, kind)) = schema.instance(group) else {
        return;
    };
    let TypeKind::Variants(variants) = kind.as_ref() else {
        return;
    };
    let group_type = rust_type(schema, group);
    let group_name = pascal_case(&definition.name);
    let arms: String = variants
        .iter()
        .map(|variant| {
            let variant_name = pascal_case(&variant.shape.text);
            let bound = bindings(&variant.shape);
            format!(
                "            {group_name}::{variant_name}{bound} => {method_error}::{variant_name}{bound},\n"
            )
        })
        .collect();
    write!(
        out,
        "impl From<{group_type}> for {method_error} {{\n    fn from(error: {group_type}) -> Self {{\n        match error {{\n{arms}        }}\n    }}\n}}\n\n"
    )
    .unwrap();
}

/// ` { a, b }` to bind a variant's parameters, or nothing.
fn bindings(shape: &Shape) -> String {
    match shape.parameters.is_empty() {
        true => String::new(),
        false => format!(
            " {{ {} }}",
            shape
                .parameters
                .iter()
                .map(|parameter| snake_case(&parameter.name))
                .collect::<Vec<_>>()
                .join(", ")
        ),
    }
}

fn parameters(schema: &Schema, parameters: &[Parameter]) -> String {
    parameters
        .iter()
        .map(|parameter| {
            format!(
                ", {}: {}",
                snake_case(&parameter.name),
                rust_type(schema, &parameter.r#type)
            )
        })
        .collect()
}

/// The Rust type of what `method` returns: `()` for `RETURNS NOTHING`.
fn returned_value(schema: &Schema, method: &Method) -> String {
    method.returns.as_ref().map_or_else(
        || "()".to_string(),
        |returns| rust_type(schema, &returns.r#type),
    )
}

fn returned(schema: &Schema, method: &Method) -> String {
    let value = returned_value(schema, method);
    match method.errors.is_empty() {
        true => value,
        false => format!("Result<{value}, {}>", error_enum_name(schema, method)),
    }
}

fn method_doc(schema: &Schema, method: &Method) -> String {
    let mut doc = doc_comment(&method.doc, "    ///");
    if !doc.is_empty() {
        doc.push_str("    ///\n");
    }
    match &method.returns {
        Some(returns) => writeln!(
            doc,
            "    /// `{}`, returning `{}`.",
            schema.call_name(method),
            returns.name
        ),
        None => writeln!(
            doc,
            "    /// `{}`, returning nothing.",
            schema.call_name(method)
        ),
    }
    .unwrap();
    doc.push_str("    ///\n");
    doc.push_str(&doc_comment(&Some(crate::effects_doc(method)), "    ///"));
    if let Some(examples) = crate::examples_doc(method) {
        doc.push_str("    ///\n");
        doc.push_str(&doc_comment(&Some(examples), "    ///"));
    }
    doc
}

/// The protocol methods in the server trait.
fn trait_methods(schema: &Schema) -> String {
    let methods: String = schema
        .methods
        .iter()
        .map(|method| {
            format!(
                "{}    async fn {}(&self{}) -> Result<{}, Self::Error>;\n\n",
                method_doc(schema, method),
                snake_case(&method_words(schema, method)),
                parameters(schema, &method.shape.parameters),
                returned(schema, method)
            )
        })
        .collect();
    methods.trim_end_matches('\n').to_string() + "\n"
}

fn root_server(out: &mut String, schema: &Schema) {
    write!(
        out,
        "/// The protocol methods, for a server to implement. An `Err` is the server's own failure: the\n/// caller gets `INTERNAL ERROR`, and the calls after it don't run.\n#[allow(async_fn_in_trait)]\npub trait Server {{\n    type Error;\n\n{}}}\n\n",
        trait_methods(schema)
    )
    .unwrap();
}

fn handle(out: &mut String, schema: &Schema) {
    let arms: String = schema
        .methods
        .iter()
        .enumerate()
        .map(|(index, method)| {
            let arguments: String = method
                .shape
                .parameters
                .iter()
                .map(|_| ", anyx_protocol::server::argument(&mut arguments)")
                .collect();
            let wrap = if method.errors.is_empty() {
                "value"
            } else {
                "result"
            };
            format!(
                "            {index} => anyx_protocol::server::{wrap}(<S as Server>::{}(implementation{arguments}).await),\n",
                snake_case(&method_words(schema, method))
            )
        })
        .collect();
    write!(
        out,
        "/// Runs `request` against `implementation` and writes the response. Every\n/// call runs, in order, until one fails with an internal error, which\n/// `on_internal_error` hears; the calls after it don't run.\n\
         pub async fn handle<S: Server>(implementation: &S, request: &str, mut on_internal_error: impl FnMut(<S as Server>::Error)) -> String {{\n\
         \x20   let schema = schema();\n\
         \x20   let calls = match anyx_protocol::server::read_request(schema, request) {{\n        Ok(calls) => calls,\n        Err(response) => return response,\n    }};\n\
         \x20   let mut outcomes = Vec::new();\n\
         \x20   let mut stopped = false;\n\
         \x20   for call in &calls {{\n\
         \x20       if stopped {{\n            outcomes.push(anyx_protocol::Outcome::NotRun);\n            continue;\n        }}\n\
         \x20       let mut arguments = call.arguments.clone().into_iter();\n\
         \x20       let outcome = match call.method {{\n{arms}            _ => Ok::<_, <S as Server>::Error>(anyx_protocol::server::built_in(schema, call).expect(\"the codec read a method of the schema\")),\n        }};\n\
         \x20       let outcome = outcome.unwrap_or_else(|error| {{\n            on_internal_error(error);\n            stopped = true;\n            anyx_protocol::Outcome::InternalError\n        }});\n\
         \x20       if anyx_protocol::server::validate_outcome(schema, call, &outcome).is_err() {{\n            stopped = true;\n            outcomes.push(anyx_protocol::Outcome::InternalError);\n        }} else {{\n            outcomes.push(outcome);\n        }}\n    }}\n\
         \x20   anyx_protocol::server::respond(schema, &calls, outcomes)\n}}\n\n",
    )
    .unwrap();
}

/// A constant of each method's markers, `READ_EFFECTS` for `read _`, for a
/// tool to decide whether to retry a call or ask before sending it.
fn effects(out: &mut String, schema: &Schema, methods: &[(usize, &Method)]) {
    for (_, method) in methods {
        let undone_by = match &method.undone_by {
            Some(undo) => format!("Some({:?})", undo.text),
            None => "None".to_string(),
        };
        write!(
            out,
            "/// What a call of `{}` may do. {}\npub const {}_EFFECTS: anyx_protocol::client::Effects = anyx_protocol::client::Effects {{\n    read_only: {},\n    idempotent: {},\n    undone_by: {undone_by},\n}};\n\n",
            schema.call_name(method),
            crate::effects_doc(method),
            snake_case(&method_words(schema, method)).to_uppercase(),
            method.effect.read_only(),
            method.effect.idempotent(),
        )
        .unwrap();
    }
}

/// The client owns its transport.
fn client(out: &mut String, schema: &Schema) {
    let methods: String = schema.methods.iter().enumerate()
        .map(|(index, method)| {
            let errors = match method.errors.is_empty() {
                true => "::std::convert::Infallible".to_string(),
                false => error_enum_name(schema, method),
            };
            let arguments = method
                .shape
                .parameters
                .iter()
                .map(|parameter| format!("{}.into_value()", snake_case(&parameter.name)))
                .collect::<Vec<_>>()
                .join(", ");
            let full = snake_case(&method_words(schema, method));
            let shorter: String = crate::shorter_forms(method)
                .into_iter()
                .map(|(form, written)| {
                    let written_parameters: Vec<Parameter> = written
                        .iter()
                        .map(|index| method.shape.parameters[*index].clone())
                        .collect();
                    let forwarded = (0..method.shape.parameters.len())
                        .map(|parameter| match written.contains(&parameter) {
                            true => snake_case(&method.shape.parameters[parameter].name),
                            false => format!(
                                "anyx_protocol::client::default(schema(), {index}, {parameter})"
                            ),
                        })
                        .collect::<Vec<_>>()
                        .join(", ");
                    format!(
                        "    /// `{}`: [`Self::{full}`] with each part left out at its default.\n    pub async fn {}(&self{}) -> Result<{}, CallError<{errors}, T::Error>> {{\n        self.{full}({forwarded}).await\n    }}\n\n",
                        form.text,
                        snake_case(&crate::form_words(schema, method, &form)),
                        parameters(schema, &written_parameters),
                        returned_value(schema, method),
                    )
                })
                .collect();
            format!(
                "{}    pub async fn {full}(&self{}) -> Result<{}, CallError<{errors}, T::Error>> {{\n        anyx_protocol::client::call(&self.transport, schema(), {index}, vec![{arguments}]).await\n    }}\n\n{shorter}",
                method_doc(schema, method),
                parameters(schema, &method.shape.parameters),
                returned_value(schema, method),
            )
        })
        .collect();
    let introspection = format!(
        "    /// `SCHEMA`, returning the guide to the schema.\n    pub async fn schema(&self) -> Result<String, CallError<::std::convert::Infallible, T::Error>> {{\n        anyx_protocol::client::call(&self.transport, schema(), {}, vec![]).await\n    }}\n\n    /// `SCHEMA FILES`, returning the files of the schema, the entry first.\n    pub async fn schema_files(&self) -> Result<Vec<SchemaFile>, CallError<::std::convert::Infallible, T::Error>> {{\n        anyx_protocol::client::call(&self.transport, schema(), {}, vec![]).await\n    }}\n\n",
        schema.introspection(),
        schema.schema_files(),
    );
    let members = (methods + &introspection)
        .trim_end_matches('\n')
        .to_string()
        + "\n";
    write!(
            out,
            "/// Calls the methods of the schema through a [`Transport`], one call per\n/// request.\npub struct Client<T> {{\n    pub transport: T,\n}}\n\n\
             impl<T: Transport> Client<T> {{\n    pub fn new(transport: T) -> Self {{\n        Self {{ transport }}\n    }}\n\n{members}}}\n\n"
        )
    .unwrap();
}
