//! The TypeScript client of a schema: its types as JSON, and a `Client` that
//! encodes and decodes through the wasm functions of [`crate::wasm`]. A
//! scope's methods are an object on the client, named after the scope.
//!
//! JSON carries an `INSTANT` as text, and the client gives it as a `Date`:
//! for each type that holds one, a `revive` function turns its JSON into
//! its value.

use std::fmt::Write;

use anyx_protocol::Schema;
use anyx_protocol::schema::{Field, Method, Shaped, Type, TypeKind, scoped};

use crate::names::camel_case;
use crate::{Error, children, has_methods, methods_in, scoped_pascal_case, typescript_error_name};

pub fn typescript(schema: &Schema) -> Result<String, Error> {
    crate::check_names(schema)?;
    let mut out = String::new();
    writeln!(
        out,
        "// Generated by anyx-protocol-generate from the `{}` schema. To change it, change the schema and generate it again.\n",
        schema.name
    )
    .unwrap();
    for definition in &schema.types {
        out.push_str(&doc(&definition.doc, ""));
        let name = scoped_pascal_case(&definition.scope, &definition.name);
        match &definition.kind {
            TypeKind::Record(fields) => record(&mut out, schema, &name, fields),
            TypeKind::Choice(variants) => union(&mut out, schema, &name, variants),
            TypeKind::Distinct(underlying) => branded(
                &mut out,
                schema,
                &name,
                &scoped(&definition.scope, &definition.name),
                underlying,
            ),
        }
    }
    for method in &schema.methods {
        if !method.errors.is_empty() {
            writeln!(out, "/** The errors of `{}`. */", method.full_name()).unwrap();
            let errors: Vec<Shaped> = schema.errors_of(method).into_iter().cloned().collect();
            union(&mut out, schema, &typescript_error_name(method), &errors);
        }
    }
    let revivers = Revivers::new(schema);
    for (index, definition) in schema.types.iter().enumerate() {
        if revivers.holds[index] {
            let name = scoped_pascal_case(&definition.scope, &definition.name);
            match &definition.kind {
                TypeKind::Record(fields) => {
                    revive_record(&mut out, schema, &revivers, &name, fields)
                }
                TypeKind::Choice(variants) => {
                    revive_union(&mut out, schema, &revivers, &name, variants)
                }
                // Revived by the reviver of the type underneath, in `of`.
                TypeKind::Distinct(_) => {}
            }
        }
    }
    for method in &schema.methods {
        let errors: Vec<Shaped> = schema.errors_of(method).into_iter().cloned().collect();
        if revivers.union_holds(&errors) {
            revive_union(
                &mut out,
                schema,
                &revivers,
                &typescript_error_name(method),
                &errors,
            );
        }
    }
    out.push_str(PRELUDE);
    let root_methods: Vec<String> = methods_in(schema, &[])
        .into_iter()
        .map(|(_, method)| {
            let signature = signature(schema, &revivers, method);
            format!(
                "{}  {}({}): {} {{\n    return this.call({:?}, [{}]{});\n  }}\n",
                doc(&method_doc(method), "  "),
                camel_case(&method.shape.text),
                signature.parameters,
                signature.returned,
                method.full_name(),
                signature.arguments,
                signature.revivers,
            )
        })
        .collect();
    let scopes: Vec<String> = children(schema, &[])
        .into_iter()
        .filter(|child| has_methods(schema, child))
        .map(|child| {
            format!(
                "  readonly {} = {};\n",
                camel_case(child.last().expect("a child scope has a name")),
                scope_object(schema, &revivers, &child, "  ")
            )
        })
        .collect();
    let introspection = "  /** `SCHEMA`, returning the guide to the schema. */\n  schema(): Promise<Outcome<string, never>> {\n    return this.call(\"SCHEMA\", []);\n  }\n".to_string();
    out.push_str(
        &root_methods
            .into_iter()
            .chain([introspection])
            .chain(scopes)
            .collect::<Vec<_>>()
            .join("\n"),
    );
    out.push_str("}\n");
    Ok(out)
}

struct Signature {
    parameters: String,
    arguments: String,
    returned: String,
    /// What `call` takes after the arguments to revive the value and the
    /// error: `, reviveFile`, or nothing when neither holds an `INSTANT`.
    revivers: String,
}

fn signature(schema: &Schema, revivers: &Revivers, method: &Method) -> Signature {
    let value = method
        .returns
        .as_ref()
        .and_then(|returns| revivers.of(schema, &returns.r#type));
    let errors: Vec<Shaped> = schema.errors_of(method).into_iter().cloned().collect();
    let error = revivers
        .union_holds(&errors)
        .then(|| format!("revive{}", typescript_error_name(method)));
    let revive = match (value, error) {
        (None, None) => String::new(),
        (Some(value), None) => format!(", {value}"),
        (value, Some(error)) => format!(
            ", {}, {error}",
            value.unwrap_or_else(|| "undefined".to_string())
        ),
    };
    let parameters = &method.shape.parameters;
    let errors = match method.errors.is_empty() {
        true => "never".to_string(),
        false => typescript_error_name(method),
    };
    Signature {
        parameters: parameters
            .iter()
            .map(|parameter| {
                format!(
                    "{}: {}",
                    camel_case(&parameter.name),
                    ts_type(schema, &parameter.r#type)
                )
            })
            .collect::<Vec<_>>()
            .join(", "),
        arguments: parameters
            .iter()
            .map(|parameter| camel_case(&parameter.name))
            .collect::<Vec<_>>()
            .join(", "),
        returned: format!(
            "Promise<Outcome<{}, {errors}>>",
            method.returns.as_ref().map_or_else(
                || "void".to_string(),
                |returns| ts_type(schema, &returns.r#type)
            )
        ),
        revivers: revive,
    }
}

/// The object of a scope's methods, and the objects of the scopes in it, on
/// the client: `client.files.export.pdf(path)`.
fn scope_object(schema: &Schema, revivers: &Revivers, scope: &[String], indent: &str) -> String {
    let inner = format!("{indent}  ");
    let methods = methods_in(schema, scope).into_iter().map(|(_, method)| {
        let signature = signature(schema, revivers, method);
        format!(
            "{}{inner}{}: ({}): {} =>\n{inner}  this.call({:?}, [{}]{}),\n",
            doc(&method_doc(method), &inner),
            camel_case(&method.shape.text),
            signature.parameters,
            signature.returned,
            method.full_name(),
            signature.arguments,
            signature.revivers,
        )
    });
    let scopes = children(schema, scope)
        .into_iter()
        .filter(|child| has_methods(schema, child))
        .map(|child| {
            format!(
                "{inner}{}: {},\n",
                camel_case(child.last().expect("a child scope has a name")),
                scope_object(schema, revivers, &child, &inner)
            )
        });
    format!(
        "{{\n{}{indent}}}",
        methods.chain(scopes).collect::<String>()
    )
}

const PRELUDE: &str = r#"/** What came of one call. */
export type Outcome<T, E> =
  | { kind: "value"; value: T }
  | { kind: "error"; error: E }
  /** An earlier call failed with an internal error, so this one didn't run. */
  | { kind: "notRun" }
  /** The server failed. It logged why. */
  | { kind: "internalError" }
  /** The server couldn't read the request. */
  | { kind: "invalidRequest"; line: number; column: number; message: string };

/** The generated wasm functions, which encode and decode in Rust. */
export interface Codec {
  /** Writes a request from a JSON array of `{ method, arguments }`. */
  encodeRequest(calls: string): string;
  /** Reads a response as a JSON array of `Outcome`s, one per method of the
   * JSON array `methods`. */
  decodeResponse(methods: string, response: string): string;
}

/** Turns the JSON of a type that holds an `INSTANT` into its value, with a
 * `Date` for each instant. */
type Reviver = (json: any) => unknown;

function reviveInstant(json: string): Date {
  return new Date(json);
}

/** `outcome` with its value or error revived. */
function revive(outcome: Outcome<never, never>, value?: Reviver, error?: Reviver): Outcome<never, never> {
  if (outcome.kind === "value" && value) return { ...outcome, value: value(outcome.value) as never };
  if (outcome.kind === "error" && error) return { ...outcome, error: error(outcome.error) as never };
  return outcome;
}

/** A call waiting for its request to be sent. */
interface QueuedCall {
  method: string;
  arguments: unknown[];
  value?: Reviver;
  error?: Reviver;
  resolve: (outcome: Outcome<never, never>) => void;
  reject: (reason: unknown) => void;
}

/** Calls the schema's methods: each call is a request of its own, and the
 * calls made in `batch` share one. `send` sends a request and returns the
 * response, such as with `fetch`. */
export class Client {
  private readonly codec: Codec;
  private readonly send: (request: string) => Promise<string>;
  /** Inside `batch`, where its calls wait to be sent together. */
  private queue: QueuedCall[] | null = null;

  constructor(codec: Codec, send: (request: string) => Promise<string>) {
    this.codec = codec;
    this.send = send;
  }

  /**
   * Sends every call `build` makes on `calls` as one request, in order, and
   * resolves to their outcomes. After a call fails with an internal error
   * the rest don't run (`notRun`).
   */
  async batch<R>(build: (calls: Client) => Promise<R>[]): Promise<R[]> {
    const calls = new Client(this.codec, this.send);
    const queue: QueuedCall[] = [];
    calls.queue = queue;
    const outcomes = build(calls);
    calls.queue = null;
    if (queue.length > 0) void this.sendCalls(queue);
    return Promise.all(outcomes);
  }

  /** Calls a method by its full name, such as `files/read _`. `value` and
   * `error` revive what it returns and its error. */
  private call<T, E>(
    method: string,
    args: unknown[],
    value?: Reviver,
    error?: Reviver,
  ): Promise<Outcome<T, E>> {
    return new Promise<Outcome<T, E>>((resolve, reject) => {
      const call = { method, arguments: args, value, error, resolve, reject };
      if (this.queue) this.queue.push(call);
      else void this.sendCalls([call]);
    });
  }

  private async sendCalls(calls: QueuedCall[]): Promise<void> {
    try {
      const request = this.codec.encodeRequest(
        JSON.stringify(calls.map((call) => ({ method: call.method, arguments: call.arguments }))),
      );
      const response = await this.send(request);
      const outcomes = JSON.parse(
        this.codec.decodeResponse(JSON.stringify(calls.map((call) => call.method)), response),
      ) as Outcome<never, never>[];
      for (const [index, call] of calls.entries()) {
        const outcome = outcomes[index];
        if (outcome) call.resolve(revive(outcome, call.value, call.error));
        else call.reject(new Error(`no outcome for ${call.method}`));
      }
    } catch (error) {
      for (const call of calls) call.reject(error);
    }
  }

"#;

fn ts_type(schema: &Schema, r#type: &Type) -> String {
    match r#type {
        Type::Text => "string".to_string(),
        // The JSON the wasm bindings speak carries bytes as base64.
        Type::Bytes => "string".to_string(),
        Type::Integer | Type::Number => "number".to_string(),
        Type::Boolean => "boolean".to_string(),
        Type::Instant => "Date".to_string(),
        // Whole milliseconds, as the JSON carries it.
        Type::Duration => "number".to_string(),
        Type::List(item) => format!("{}[]", ts_type(schema, item)),
        Type::Map(value) => format!("Record<string, {}>", ts_type(schema, value)),
        Type::Named(index) => {
            let definition = &schema.types[*index];
            scoped_pascal_case(&definition.scope, &definition.name)
        }
    }
}

/// A method's doc, then its examples.
fn method_doc(method: &Method) -> Option<String> {
    match (&method.doc, crate::examples_doc(method)) {
        (Some(doc), Some(examples)) => Some(format!("{doc}\n\n{examples}")),
        (doc, examples) => examples.or_else(|| doc.clone()),
    }
}

fn doc(doc: &Option<String>, indent: &str) -> String {
    let Some(doc) = doc else { return String::new() };
    let doc = doc.replace("*/", "*\\/");
    let lines: Vec<&str> = doc.lines().collect();
    match lines.as_slice() {
        [line] => format!("{indent}/** {line} */\n"),
        lines => {
            let body: String = lines
                .iter()
                .map(|line| match line.is_empty() {
                    true => format!("{indent} *\n"),
                    false => format!("{indent} * {line}\n"),
                })
                .collect();
            format!("{indent}/**\n{body}{indent} */\n")
        }
    }
}

fn record(out: &mut String, schema: &Schema, name: &str, fields: &[Field]) {
    writeln!(out, "export interface {name} {{").unwrap();
    for field in fields {
        out.push_str(&doc(&field.doc, "  "));
        let optional = if crate::rust::may_be_missing(field) {
            "?"
        } else {
            ""
        };
        writeln!(
            out,
            "  {}{optional}: {};",
            camel_case(&field.name),
            ts_type(schema, &field.r#type)
        )
        .unwrap();
    }
    out.push_str("}\n\n");
}

/// A named type: the type underneath, branded with the named type's full
/// name so that another named type over the same type doesn't fit it, and a
/// function of the same name that brands a value. The JSON is the value
/// underneath.
fn branded(out: &mut String, schema: &Schema, name: &str, full_name: &str, underlying: &Type) {
    let underlying = ts_type(schema, underlying);
    writeln!(
        out,
        "export type {name} = {underlying} & {{ readonly __brand: {full_name:?} }};\n"
    )
    .unwrap();
    writeln!(
        out,
        "/** Makes a `{name}` of a value, which the schema writes as its own. */\nexport function {name}(value: {underlying}): {name} {{\n  return value as {name};\n}}\n"
    )
    .unwrap();
}

/// A choice, or a method's errors: a union discriminated by `kind`.
fn union(out: &mut String, schema: &Schema, name: &str, variants: &[Shaped]) {
    writeln!(out, "export type {name} =").unwrap();
    for variant in variants {
        out.push_str(&doc(&variant.doc, "  "));
        let parameters: String = variant
            .shape
            .parameters
            .iter()
            .map(|parameter| {
                format!(
                    "; {}: {}",
                    camel_case(&parameter.name),
                    ts_type(schema, &parameter.r#type)
                )
            })
            .collect();
        writeln!(
            out,
            "  | {{ kind: {:?}{parameters} }}",
            camel_case(&variant.shape.words())
        )
        .unwrap();
    }
    out.truncate(out.trim_end().len());
    out.push_str(";\n\n");
}

/// Which of the schema's types hold an `INSTANT`, directly or through
/// another type (a named `TYPE` through the type underneath), and so need
/// reviving.
struct Revivers {
    holds: Vec<bool>,
}

impl Revivers {
    fn new(schema: &Schema) -> Self {
        let mut revivers = Revivers {
            holds: vec![false; schema.types.len()],
        };
        loop {
            let found: Vec<usize> = (0..schema.types.len())
                .filter(|index| !revivers.holds[*index])
                .filter(|index| match &schema.types[*index].kind {
                    TypeKind::Record(fields) => fields
                        .iter()
                        .any(|field| revivers.type_holds(&field.r#type)),
                    TypeKind::Choice(variants) => revivers.union_holds(variants),
                    TypeKind::Distinct(underlying) => revivers.type_holds(underlying),
                })
                .collect();
            if found.is_empty() {
                return revivers;
            }
            for index in found {
                revivers.holds[index] = true;
            }
        }
    }

    fn type_holds(&self, r#type: &Type) -> bool {
        match r#type {
            Type::Instant => true,
            Type::List(item) | Type::Map(item) => self.type_holds(item),
            Type::Named(index) => self.holds[*index],
            _ => false,
        }
    }

    fn union_holds(&self, variants: &[Shaped]) -> bool {
        variants.iter().any(|variant| {
            variant
                .shape
                .parameters
                .iter()
                .any(|parameter| self.type_holds(&parameter.r#type))
        })
    }

    /// A function that revives the JSON of `type`, or `None` when it holds
    /// no `INSTANT`.
    fn of(&self, schema: &Schema, r#type: &Type) -> Option<String> {
        match r#type {
            Type::Instant => Some("reviveInstant".to_string()),
            Type::List(item) => self
                .of(schema, item)
                .map(|item| format!("(json: any[]) => json.map({item})")),
            Type::Map(value) => self.of(schema, value).map(|value| {
                let revived = match value.contains(' ') {
                    true => format!("({value})(item)"),
                    false => format!("{value}(item)"),
                };
                format!(
                    "(json: Record<string, any>) => Object.fromEntries(Object.entries(json).map(([key, item]) => [key, {revived}]))"
                )
            }),
            Type::Named(index) if self.holds[*index] => {
                let definition = &schema.types[*index];
                if let TypeKind::Distinct(underlying) = &definition.kind {
                    // A brand is only a type, so the value underneath is
                    // revived as it is.
                    return self.of(schema, underlying);
                }
                Some(format!(
                    "revive{}",
                    scoped_pascal_case(&definition.scope, &definition.name)
                ))
            }
            _ => None,
        }
    }

    /// `json`, revived as `type`.
    fn apply(&self, schema: &Schema, r#type: &Type, json: &str) -> Option<String> {
        self.of(schema, r#type)
            .map(|reviver| match reviver.contains(' ') {
                true => format!("({reviver})({json})"),
                false => format!("{reviver}({json})"),
            })
    }
}

fn revive_record(
    out: &mut String,
    schema: &Schema,
    revivers: &Revivers,
    name: &str,
    fields: &[Field],
) {
    let revived: String = fields
        .iter()
        .filter_map(|field| {
            let key = camel_case(&field.name);
            let json = format!("json.{key}");
            let value = revivers.apply(schema, &field.r#type, &json)?;
            Some(match crate::rust::may_be_missing(field) {
                true => format!(", {key}: {json} === undefined ? undefined : {value}"),
                false => format!(", {key}: {value}"),
            })
        })
        .collect();
    writeln!(
        out,
        "function revive{name}(json: any): {name} {{\n  return {{ ...json{revived} }};\n}}\n"
    )
    .unwrap();
}

fn revive_union(
    out: &mut String,
    schema: &Schema,
    revivers: &Revivers,
    name: &str,
    variants: &[Shaped],
) {
    let cases: String = variants
        .iter()
        .filter_map(|variant| {
            let revived: String = variant
                .shape
                .parameters
                .iter()
                .filter_map(|parameter| {
                    let key = camel_case(&parameter.name);
                    let value =
                        revivers.apply(schema, &parameter.r#type, &format!("json.{key}"))?;
                    Some(format!(", {key}: {value}"))
                })
                .collect();
            (!revived.is_empty()).then(|| {
                format!(
                    "    case {:?}:\n      return {{ ...json{revived} }};\n",
                    camel_case(&variant.shape.words())
                )
            })
        })
        .collect();
    writeln!(
        out,
        "function revive{name}(json: any): {name} {{\n  switch (json.kind) {{\n{cases}    default:\n      return json;\n  }}\n}}\n"
    )
    .unwrap();
}
